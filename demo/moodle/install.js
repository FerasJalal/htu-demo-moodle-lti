// One-shot setup of the local HTU-style Moodle (Docker) wired to Rennix.
// Safe to re-run: every step checks before it changes anything.
//
//   1. moodle/.env with random local passwords (if missing)
//   2. docker compose up, wait for Moodle's first install
//   3. config.php fixes: reverse proxy (published on 8085, nginx on 8080) and
//      its own session cookie name (so another local Moodle on :8080 can't clash)
//   4. Tiles course format (fetched from its author's repo) + local_rennixtutorbot
//      (from the sibling ../../local_rennixtutorbot checkout)
//   5. setup-htu.php: users, LTI 1.3 tools -> setup-result.txt (client/deployment ids)
//      setup-htu-look.php: HTU look, courses, video page, Tutor Bot video panel
//   6. plugin settings (Rennix LTI URL, video tracking)
//
// Then run `node start-all.js` from the folder above (registers this Moodle in
// rennix-lti automatically) and `node seed-demo.js` to link the demo video.
// Usage: node install.js

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const HERE = __dirname;
const CONTAINER = 'rennix-local-moodle-moodle-1';
const PLUGIN_SRC = path.join(HERE, '..', '..', 'local_rennixtutorbot');
const TILES_DIR = path.join(HERE, 'assets', 'tiles');
const RENNIX_LTI_URL = process.env.RENNIX_LTI_URL || 'http://localhost:3002';
const run = (cmd, args, opts = {}) => execFileSync(cmd, args, {
  encoding: 'utf8', stdio: opts.quiet ? 'pipe' : ['ignore', 'pipe', 'inherit'],
  env: { ...process.env, MSYS_NO_PATHCONV: '1' }, cwd: HERE, ...opts,
});
const dockerExec = (args, opts) => run('docker', ['exec', ...args], opts);
const php = (code, extraEnv = []) => dockerExec([...extraEnv.flatMap((e) => ['-e', e]), CONTAINER, 'php', '-r', code]);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const step = (msg) => console.log(`\n== ${msg}`);

async function main() {
  step('Local passwords');
  const envFile = path.join(HERE, '.env');
  if (!fs.existsSync(envFile)) {
    const r = () => crypto.randomBytes(12).toString('base64url');
    fs.writeFileSync(envFile, [
      '# Local-dev-only credentials, generated by install.js. Not real accounts anywhere else.',
      `DB_PASS=${r()}`, `MOODLE_ADMIN_PASSWORD=Adm-${r()}1!`, `TEACHER_PASSWORD=Tch-${r()}1!`, `STUDENT_PASSWORD=Stu-${r()}1!`, '',
    ].join('\n'));
    console.log('created moodle/.env (usernames: admin, teacher1, student1)');
  } else {
    console.log('moodle/.env already exists, keeping it');
  }
  const env = Object.fromEntries(fs.readFileSync(envFile, 'utf8').split(/\r?\n/)
    .filter((l) => /^[A-Z_]+=/.test(l)).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]));

  step('Starting Moodle + Postgres (first run downloads ~325 MB of images)');
  run('docker', ['compose', 'up', '-d']);
  process.stdout.write('waiting for Moodle to finish installing');
  for (let i = 0; ; i++) {
    try {
      const r = await fetch('http://localhost:8085/login/index.php', { redirect: 'manual' });
      if (r.status === 200 || r.status === 303) break;
    } catch (e) { /* not up yet */ }
    if (i > 120) throw new Error('Moodle did not come up within 10 minutes -- see `docker compose logs moodle`');
    process.stdout.write('.');
    await sleep(5000);
  }
  console.log(' up');

  step('config.php fixes');
  dockerExec([CONTAINER, 'sh', '-c',
    "grep -q 'reverseproxy = true' /var/www/html/config.php || " +
    "sed -i 's/^\\$CFG->reverseproxy[[:space:]]*=[[:space:]]*false;/$CFG->reverseproxy = true;/' /var/www/html/config.php; " +
    "grep -q sessioncookie /var/www/html/config.php || " +
    "sed -i 's|^\\$CFG->reverseproxy = true;|$CFG->reverseproxy = true;\\n$CFG->sessioncookie = \"HTULocal\";|' /var/www/html/config.php; " +
    "grep -nE 'reverseproxy|sessioncookie' /var/www/html/config.php"]);

  step('Plugins: Tiles course format + local_rennixtutorbot');
  if (!fs.existsSync(TILES_DIR)) {
    run('git', ['clone', '-q', '--depth', '1', '--branch', 'moodle51', 'https://bitbucket.org/dw8/moodle-format_tiles.git', TILES_DIR]);
  }
  if (!fs.existsSync(path.join(PLUGIN_SRC, 'version.php'))) {
    throw new Error(`local_rennixtutorbot not found at ${PLUGIN_SRC} -- clone it next to this folder (see README)`);
  }
  const owner = dockerExec([CONTAINER, 'stat', '-c', '%u:%g', '/var/www/html/public/course/format/topics'], { quiet: true }).trim();
  for (const [src, dest] of [[TILES_DIR, '/var/www/html/public/course/format/tiles'], [PLUGIN_SRC, '/var/www/html/public/local/rennixtutorbot']]) {
    dockerExec(['-u', 'root', CONTAINER, 'rm', '-rf', dest]);
    run('docker', ['cp', src, `${CONTAINER}:${dest}`]);
    dockerExec(['-u', 'root', CONTAINER, 'sh', '-c', `rm -rf ${dest}/.git && chown -R ${owner} ${dest}`]);
  }
  dockerExec([CONTAINER, 'php', '/var/www/html/admin/cli/upgrade.php', '--non-interactive']);

  step('Users, LTI tools, HTU look and courses');
  dockerExec([CONTAINER, 'mkdir', '-p', '/tmp/htu-assets']);
  for (const f of fs.readdirSync(path.join(HERE, 'assets')).filter((n) => /\.(png|scss|html)$/.test(n))) {
    run('docker', ['cp', path.join(HERE, 'assets', f), `${CONTAINER}:/tmp/htu-assets/${f}`]);
  }
  for (const f of ['setup-htu.php', 'setup-htu-look.php']) run('docker', ['cp', path.join(HERE, f), `${CONTAINER}:/tmp/${f}`]);
  // Passed through the environment (docker exec -e NAME), not on the command line.
  const setupOut = run('docker', ['exec', '-e', 'TEACHER_PASSWORD', '-e', 'STUDENT_PASSWORD', CONTAINER, 'php', '/tmp/setup-htu.php'], {
    quiet: true,
    env: { ...process.env, MSYS_NO_PATHCONV: '1', TEACHER_PASSWORD: env.TEACHER_PASSWORD, STUDENT_PASSWORD: env.STUDENT_PASSWORD },
  });
  const resultLine = setupOut.split(/\r?\n/).find((l) => l.startsWith('{'));
  fs.writeFileSync(path.join(HERE, 'setup-result.txt'), resultLine + '\n');
  console.log('LTI tools:', resultLine);
  dockerExec([CONTAINER, 'php', '/tmp/setup-htu-look.php'], { quiet: true });

  step('Plugin settings');
  php(`define("CLI_SCRIPT",1); require "/var/www/html/config.php";
    set_config("rennixltiurl", "${RENNIX_LTI_URL}", "local_rennixtutorbot");
    set_config("enablevideotracking", 1, "local_rennixtutorbot");
    purge_caches(); echo "done\\n";`);

  console.log('\nMoodle is ready at http://localhost:8085 (passwords in moodle/.env).');
  console.log('Next: `node start-all.js` in the folder above, then `node seed-demo.js` there.');
}

main().catch((e) => { console.error('\nFAILED:', e.message); process.exit(1); });
