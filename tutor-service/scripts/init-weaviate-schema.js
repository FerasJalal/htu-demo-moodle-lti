// Creates (idempotently) the CourseContent collection in Weaviate, using native
// Weaviate multi-tenancy (separate shard per tenant) rather than a tenant_id
// property filter -- this matches tutor-service's existing per-tenant-database
// pattern (getTenantDb()) more closely than a shared-collection filter would.
//
// Run manually: WEAVIATE_URL=... WEAVIATE_API_KEY=... node scripts/init-weaviate-schema.js

const WEAVIATE_URL = process.env.WEAVIATE_URL || 'http://localhost:8081';
const WEAVIATE_API_KEY = process.env.WEAVIATE_API_KEY;
const CLASS_NAME = 'CourseContent';

// Every tenant that should exist. Add new ones here as HTU-like deployments
// are onboarded -- this script is safe to re-run.
const TENANTS = ['HTU'];

if (!WEAVIATE_API_KEY) {
  console.error('WEAVIATE_API_KEY not set');
  process.exit(1);
}

// BGE-M3 dense embeddings are 1024-dim. Vectors are supplied by the ingestion
// pipeline (vectorizer: none / self-provided) rather than generated by
// Weaviate, so the embedding model can be swapped without touching this schema.
const SCHEMA = {
  class: CLASS_NAME,
  description:
    'Chunked course content (PDF/slide/transcript text) for RAG retrieval. Tenant isolation is native Weaviate multi-tenancy (separate shard per tenant); course_id is a property filter within a tenant.',
  vectorizer: 'none',
  multiTenancyConfig: { enabled: true },
  vectorIndexConfig: {
    distance: 'cosine',
  },
  invertedIndexConfig: {
    bm25: { b: 0.75, k1: 1.2 },
  },
  properties: [
    { name: 'text', dataType: ['text'], tokenization: 'word', indexFilterable: true, indexSearchable: true },
    { name: 'course_id', dataType: ['text'], tokenization: 'field', indexFilterable: true, indexSearchable: false },
    { name: 'source_type', dataType: ['text'], tokenization: 'field', indexFilterable: true, indexSearchable: false }, // "video_transcript" | "pdf" | "slide"
    { name: 'source_id', dataType: ['text'], tokenization: 'field', indexFilterable: true, indexSearchable: false }, // e.g. "lecture_05"
    { name: 'source_title', dataType: ['text'], tokenization: 'word', indexFilterable: true, indexSearchable: true }, // e.g. "Lecture 5"
    { name: 'video_id', dataType: ['text'], tokenization: 'field', indexFilterable: true, indexSearchable: false },
    { name: 'timestamp_start', dataType: ['number'], indexFilterable: true },
    { name: 'timestamp_end', dataType: ['number'], indexFilterable: true },
    { name: 'document_id', dataType: ['text'], tokenization: 'field', indexFilterable: true, indexSearchable: false }, // PDFs
    { name: 'page_number', dataType: ['int'], indexFilterable: true },
    { name: 'language', dataType: ['text'], tokenization: 'field', indexFilterable: true, indexSearchable: false },
    { name: 'chunk_index', dataType: ['int'], indexFilterable: true },
  ],
};

async function wf(path, options = {}) {
  const res = await fetch(`${WEAVIATE_URL}${path}`, {
    ...options,
    headers: {
      Authorization: `Bearer ${WEAVIATE_API_KEY}`,
      'Content-Type': 'application/json',
      ...(options.headers || {}),
    },
  });
  return res;
}

async function main() {
  const existing = await wf(`/v1/schema/${CLASS_NAME}`);
  if (existing.status === 200) {
    const current = await existing.json();
    if (!current.multiTenancyConfig?.enabled) {
      console.log(`Class "${CLASS_NAME}" exists but WITHOUT multi-tenancy enabled -- Weaviate can't change that on an existing class, so it must be dropped and recreated. This is destructive to any data currently in it.`);
      const del = await wf(`/v1/schema/${CLASS_NAME}`, { method: 'DELETE' });
      if (!del.ok) {
        console.error('Failed to delete old class:', await del.text());
        process.exit(1);
      }
      console.log(`Deleted old "${CLASS_NAME}" class.`);
    } else {
      console.log(`Class "${CLASS_NAME}" already exists with multi-tenancy enabled, skipping creation.`);
      await ensureTenants();
      return;
    }
  }

  const res = await wf('/v1/schema', { method: 'POST', body: JSON.stringify(SCHEMA) });
  const body = await res.json();
  if (!res.ok) {
    console.error('Failed to create class:', JSON.stringify(body, null, 2));
    process.exit(1);
  }
  console.log(`Class "${CLASS_NAME}" created with multi-tenancy enabled.`);
  await ensureTenants();
}

async function ensureTenants() {
  const res = await wf(`/v1/schema/${CLASS_NAME}/tenants`);
  const existing = res.ok ? (await res.json()).map((t) => t.name) : [];
  const missing = TENANTS.filter((t) => !existing.includes(t));
  if (missing.length === 0) {
    console.log(`All tenants already exist: ${existing.join(', ')}`);
    return;
  }
  const create = await wf(`/v1/schema/${CLASS_NAME}/tenants`, {
    method: 'POST',
    body: JSON.stringify(missing.map((name) => ({ name }))),
  });
  if (!create.ok) {
    console.error('Failed to create tenants:', await create.text());
    process.exit(1);
  }
  console.log(`Created tenants: ${missing.join(', ')}`);
}

main();
